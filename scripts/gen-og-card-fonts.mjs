// Writes server/og-card-fonts.ts: the fonts the server's share cards draw with
// (server/og-cards.ts), embedded as base64 so the production server needs no
// font files on disk and no system fonts.
//
// Geist, the app's own face (SIL Open Font License 1.1), from the
// @fontsource/geist dev dependency: the latin subset as WOFF (satori reads
// ttf, otf and woff, not woff2), at the two weights the cards use.
//
//   node scripts/gen-og-card-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(import.meta.url), "../..");
const b64 = (weight) => readFileSync(resolve(root, `node_modules/@fontsource/geist/files/geist-latin-${weight}-normal.woff`)).toString("base64");

const out = `/**
 * Fonts for server-rendered share cards (see og-cards.ts).
 *
 * Base64-embedded so the production bundle needs no font files on disk and no
 * fontconfig on the server: satori turns text into SVG outlines with these,
 * so the rasteriser never touches system fonts.
 *
 * Geist, the app's own face (SIL Open Font License 1.1), latin subset, WOFF
 * (satori reads ttf, otf and woff, not woff2), from @fontsource/geist.
 * Generated by scripts/gen-og-card-fonts.mjs; do not edit by hand.
 */

export const GEIST_400_WOFF_B64 =
  "${b64(400)}";

export const GEIST_600_WOFF_B64 =
  "${b64(600)}";
`;
writeFileSync(resolve(root, "server/og-card-fonts.ts"), out);
console.log(`wrote server/og-card-fonts.ts (${Math.round(out.length / 1024)} KB)`);
